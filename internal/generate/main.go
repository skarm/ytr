// Command generate reproduces the public methods from the reviewed catalog.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strings"

	"github.com/skarm/ytr/internal/apidoc"
)

// methodSpec describes the extra parameter, client executor, and response type of a Go method.
type methodSpec struct{ parameter, argument, clientMethod, responseType string }

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	catalog, err := apidoc.Load("api/catalog.json")
	if err != nil {
		return err
	}

	models, err := apidoc.LoadModels("api/models.json", catalog)
	if err != nil {
		return err
	}

	methods, err := renderMethods(catalog)
	if err != nil {
		return err
	}

	modelSource, err := renderTypedFile("typed/models_gen.go", modelTemplate, models)
	if err != nil {
		return err
	}

	clientSource, err := renderTypedFile("typed/client_gen.go", clientTemplate, models)
	if err != nil {
		return err
	}

	// Validate and render the complete binding set before touching any output.
	if err := os.MkdirAll("typed", 0o750); err != nil {
		return err
	}

	for _, output := range []struct {
		path string
		data []byte
	}{
		{"methods_gen.go", methods},
		{"typed/models_gen.go", modelSource},
		{"typed/client_gen.go", clientSource},
	} {
		if err := os.WriteFile(output.path, output.data, 0o644); err != nil { // #nosec G306 -- Generated public API source must be readable by build tools.
			return err
		}
	}

	return nil
}

func renderMethods(catalog apidoc.Catalog) ([]byte, error) {
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by go generate; DO NOT EDIT.\n\npackage ytr\n\nimport \"context\"")
	writeCatalog(&out, catalog)

	for index, op := range catalog.Operations {
		writeMethod(&out, op, index)
	}

	return format.Source(out.Bytes())
}

func writeCatalog(out *bytes.Buffer, c apidoc.Catalog) {
	fmt.Fprintln(out, "\nconst (")

	for _, op := range c.Operations {
		fmt.Fprintf(out, "Op%s OperationName = %q\n", op.Name, op.Name)
	}

	fmt.Fprintln(out, ")\n\nvar operations = []Operation{")

	for _, op := range c.Operations {
		doc := "https://yandex.ru/support/tracker/ru/" + op.Source + "?revision=" + c.Revision
		fmt.Fprintf(out, "{Name: Op%s, Method: %q, Path: %q, Request: %q, Response: %q, Documentation: %q},\n", op.Name, op.Method, op.Path, op.Request, op.Response, doc)
	}

	fmt.Fprintln(out, "}")
	fmt.Fprintln(out, "\nvar operationIndex = map[OperationName]int{")

	for index, op := range c.Operations {
		fmt.Fprintf(out, "Op%s: %d,\n", op.Name, index)
	}

	fmt.Fprintln(out, "}")
}

func writeMethod(out *bytes.Buffer, op apidoc.Operation, index int) {
	pathParameters := apidoc.PathParameters(op.Path)
	parameters := []string{"ctx context.Context"}
	pathArguments := make([]string, 0, len(pathParameters))

	for _, name := range pathParameters {
		parameterType := "string"

		argument := name
		if name == "entityType" {
			parameterType = "EntityType"
			argument = "string(entityType)"
		}

		parameters = append(parameters, name+" "+parameterType)
		pathArguments = append(pathArguments, argument)
	}

	spec := methodSpecFor(op)
	if spec.parameter != "" {
		parameters = append(parameters, spec.parameter)
	}

	parameters = append(parameters, "options ...CallOption")

	fmt.Fprintf(out, "\n// %s — %s.\n", op.Name, op.Summary)
	fmt.Fprintf(out, "// See https://yandex.ru/support/tracker/ru/%s\n", op.Source)
	fmt.Fprintf(out, "func (c *Client) %s(%s) (*%s, error) {\n", op.Name, strings.Join(parameters, ", "), spec.responseType)
	fmt.Fprintf(out, "return c.%s(ctx, operations[%d], []string{%s}%s, options...)\n}\n", spec.clientMethod, index, strings.Join(pathArguments, ", "), spec.argument)
}

func methodSpecFor(op apidoc.Operation) methodSpec {
	if op.Response == "stream" {
		return methodSpec{clientMethod: "download", responseType: "Download"}
	}

	if op.Request == "multipart" {
		return methodSpec{"file File", ", file", "upload", "Response"}
	}

	if op.Request == "json" {
		return methodSpec{"body any", ", body", "call", "Response"}
	}

	return methodSpec{argument: ", nil", clientMethod: "call", responseType: "Response"}
}
