func renderTypedFile(path, source string, models apidoc.Models) ([]byte, error) {
	funcs := template.FuncMap{"modelImports": modelImports, "clientImports": clientImports, "queryValue": queryValue, "pathValue": pathValue}

	tmpl, err := template.New("typed").Funcs(funcs).Parse(source)
	if err != nil {
		return nil, err
	}

	var out bytes.Buffer
	if err := tmpl.Execute(&out, models); err != nil {
		return nil, err
	}

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format %s: %w", path, err)
	}

	return formatted, nil
}

func modelImports(models apidoc.Models) []string {
	imports := map[string]bool{}

	for _, model := range models.Types {
		expressions := make([]string, 0, 1+len(model.Fields)+len(model.Variants))

		expressions = append(expressions, model.Target)
		for _, field := range model.Fields {
			expressions = append(expressions, field.Type)
		}

		for _, variant := range model.Variants {
			expressions = append(expressions, variant.Type)
		}

		if model.Open {
			imports["encoding/json"] = true
		}

		for _, expression := range expressions {
			if strings.Contains(expression, "json.") {
				imports["encoding/json"] = true
			}

			if strings.Contains(expression, "ytr.") {
				imports["github.com/skarm/ytr"] = true
			}
		}
	}

	return sortedImports(imports)
}

func clientImports(models apidoc.Models) []string {
	imports := map[string]bool{"context": true, "github.com/skarm/ytr": true}

	for _, operation := range models.Operations {
		if strings.Contains(operation.Response, "json.") {
			imports["encoding/json"] = true
		}

		if len(operation.Queries) > 0 {
			imports["net/url"] = true
		}

		for _, query := range operation.Queries {
			if query.Type == "bool" || query.Type == "int64" {
				imports["strconv"] = true
			}

			if query.Type == "[]string" {
				imports["strings"] = true
			}
		}
	}

	return sortedImports(imports)
}

func sortedImports(imports map[string]bool) []string {
	names := make([]string, 0, len(imports))
	for name := range imports {
		names = append(names, name)
	}

	slices.Sort(names)

	if index := slices.Index(names, "github.com/skarm/ytr"); index >= 0 {
		names = slices.Delete(names, index, index+1)
		names = append(names, "github.com/skarm/ytr")
	}

	return names
}

func queryValue(q apidoc.ModelQuery) string {
	value := "request." + q.Field
	if q.Optional {
		value = "*" + value
	}

	switch q.Type {
	case "bool":
		return "strconv.FormatBool(" + value + ")"
	case "int64":
		return "strconv.FormatInt(" + value + ", 10)"
	case "[]string":
		return "strings.Join(" + value + ", \",\")"
	default:
		return value
	}
}

func pathValue(p apidoc.ModelPath) string {
	if p.Type == "ytr.EntityType" {
		return "string(request." + p.Name + ")"
	}

	return "request." + p.Name
}

